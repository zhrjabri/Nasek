/*
 * Concatenate every migration, in order, into one file.
 *
 * The Supabase CLI applies `supabase/migrations/` one file at a time and keeps
 * a record of what it has run — that is the right way to do this, and what
 * `supabase db push` is for. But it needs the CLI installed, a project link and
 * the database password, and the dashboard's SQL editor needs none of those.
 * Pasting five files in the correct order by hand is where that shortcut goes
 * wrong, so this produces one file that is already in the correct order.
 *
 *   npm run db:bundle        # writes supabase/all-migrations.sql
 *
 * The output is gitignored. It is generated, never edited: change a migration
 * and re-run this, or the two drift and the bundle silently becomes the older
 * truth.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'supabase', 'migrations')
const out = path.join(root, 'supabase', 'all-migrations.sql')

const files = fs.readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()
if (!files.length) {
  console.error('No migrations found in supabase/migrations/')
  process.exit(1)
}

const header = `-- =============================================================================
-- NASEK — every migration, concatenated in order.
--
-- GENERATED by scripts/bundle-migrations.mjs. Do not edit; edit the files in
-- supabase/migrations/ and re-run \`npm run db:bundle\`.
--
-- Paste the whole of this into the Supabase dashboard's SQL Editor and run it
-- once. Every statement is written to be safely re-runnable, so if it stops
-- part way you can fix the cause and run the whole thing again.
--
-- ONE THING THAT CAN GO WRONG HERE AND NOWHERE ELSE
--
-- The SQL Editor runs everything below as a single implicit transaction, while
-- \`supabase db push\` runs each file in its own. Postgres will not let a value
-- added to an enum be *used* in the transaction that added it — so if it stops
-- with "unsafe use of new value of enum type", run
-- 20260902000100_provider_status_values.sql on its own first, then this file
-- again. Nothing is lost by doing that: every statement is re-runnable.
--
-- Source files, in order:
${files.map((f, i) => `--   ${i + 1}. ${f}`).join('\n')}
-- =============================================================================

`

const body = files
  .map(
    (f) =>
      `\n-- ${'='.repeat(76)}\n-- BEGIN ${f}\n-- ${'='.repeat(76)}\n\n` +
      fs.readFileSync(path.join(dir, f), 'utf8').trimEnd() +
      `\n\n-- END ${f}\n`,
  )
  .join('\n')

fs.writeFileSync(out, header + body, 'utf8')

const lines = (header + body).split('\n').length
console.log(`Wrote ${path.relative(root, out)}`)
console.log(`  ${files.length} migrations, ${lines} lines`)
console.log('\nPaste it into: Supabase dashboard -> SQL Editor -> New query -> Run')
